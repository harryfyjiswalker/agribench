"""Frozen Copernicus-FM (ViT-B/16) patch embeddings for every YieldSAT pixel (protocols/yieldsat.md, 2.5).

Copernicus-FM (Wang et al. 2025, arXiv:2503.11849) is a ViT whose patch embedding is generated by a hypernetwork
from each band's wavelength and bandwidth, pretrained (MAE + distillation) on Copernicus-Pretrain (S1, S2, S3, S5P,
DEM). Its position embedding can add the image's lon/lat, date and area. Here: the peak-greenness scene (12 L2A
bands, wavelengths/bandwidths from Copernicus-Bench), z-scored with the SSL4EO-S12 statistics Copernicus-Bench
uses, 224 px windows, 16 px tokens. Metadata: the scene date and the window area (5.0176 km2) are given; lon/lat are
withheld (the model's learned "unknown" token), so location enters only through the location-encoder inputs.

Model code: torchgeo (benchmark-v2) CopernicusFM; weights pinned under upstream/copernicus-fm/weights.

    python -m tools.patch_embed --subset GER-W                      (dates, CPU, once per subset)
    python -m tools.embed_yieldsat_copernicusfm --subset GER-W      (one subset per array task)
"""
import datetime as dt

import numpy as np
import torch

from tools import patch_embed as pe
from tools import yieldsat as ys

WEIGHTS = ys.PROJECT / "upstream" / "copernicus-fm" / "weights" / "CopernicusFM_ViT_base_varlang-085350e4.pth"
SIZE, TOKEN = 224, 16
AREA_KM2 = (SIZE * 10 / 1000) ** 2
EPOCH = dt.date(1970, 1, 1)


def make_model():
    import torchgeo
    from torchgeo.models import CopernicusFM
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    net = CopernicusFM(embed_dim=768, depth=12, num_heads=12, global_pool=True)
    missing, unexpected = net.load_state_dict(pe.load_state(WEIGHTS), strict=False)
    if set(missing) - {"fc_norm.weight", "fc_norm.bias", "head.weight", "head.bias"} or unexpected:
        raise ValueError(f"Copernicus-FM weights: missing {missing}, unexpected {unexpected}")
    net = net.to(device).eval()
    store = pe.capture_output(net.blocks[-1])  # checkpoint has no final norm

    def encode(x, dates):
        days = torch.tensor([(d - EPOCH).days for d in dates], dtype=x.dtype, device=x.device)
        meta = torch.stack([torch.full_like(days, float("nan")), torch.full_like(days, float("nan")), days,
                            torch.full_like(days, AREA_KM2)], 1)
        net.forward_features(x, meta, wavelengths=pe.WAVELENGTH_NM, bandwidths=pe.BANDWIDTH_NM,
                             input_mode="spectral", kernel_size=TOKEN)
        return pe.tokens_to_grid(store["x"][:, 1:], SIZE // TOKEN)

    return pe.Model("copernicusfm", 768, SIZE, TOKEN, lambda img: pe.zscore(img).astype(np.float32), encode, {
        "model": "Copernicus-FM ViT-B/16 (varlang), torchgeo CopernicusFM",
        "revision": {"torchgeo": torchgeo.__version__, "weights_sha256": pe.weights_sha(WEIGHTS),
                     "weights_url": "https://huggingface.co/torchgeo/copernicus-fm/resolve/"
                                    "f395812cc990ba25a451dbb9c9e6d95c8482947e/CopernicusFM_ViT_base_varlang-085350e4.pth"},
        "settings": {"modalities": "S2 L2A 12 bands (no S1 in YieldSAT)", "normalization": "SSL4EO-S12 z-score",
                     "wavelengths_nm": pe.WAVELENGTH_NM, "bandwidths_nm": pe.BANDWIDTH_NM,
                     "metadata": "date (days since 1970) and window area given; lon/lat withheld (NaN)",
                     "layer": "last transformer block output (the checkpoint has no final norm)"}})


if __name__ == "__main__":
    pe.cli(make_model)
